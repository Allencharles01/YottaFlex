#!/usr/bin/env bash
# Regenerate the hash-pinned lockfiles from the project venv (DECISIONS.md #103, #127).
#
# The lockfiles pin exactly the versions installed in .venv, i.e. the versions the test suite
# ran against: `pip freeze` is passed to the resolver as constraints, so it may not pick newer
# releases. Every pin carries the sha256 of its distribution files (`--generate-hashes`), so
# `pip install --require-hashes` refuses anything that differs. Needs `uv` and network access.
#
# Usage (from the project root, venv active):  scripts/lock_dependencies.sh
set -euo pipefail

cd "$(dirname "$0")/.."
constraints="$(mktemp)"
trap 'rm -f "$constraints"' EXIT
python -m pip freeze --exclude-editable > "$constraints"

compile() {  # <output file> [--extra NAME ...]
  local output="$1"
  shift
  uv pip compile pyproject.toml "$@" \
    --python-version 3.12 --python-platform x86_64-unknown-linux-gnu \
    --constraint "$constraints" --generate-hashes --no-header --quiet --output-file "$output.tmp"
  {
    echo "# Hash-pinned lockfile for the YottaFlex coldchain package (Python 3.12, Linux x86_64)."
    echo "# Generated by scripts/lock_dependencies.sh from the tested venv; do not edit by hand."
    echo "# Install: pip install --require-hashes -r $output && pip install --no-deps -e ."
    # Drop the "-c /tmp/tmp.XXXX" provenance comments: the constraint file has a random name,
    # which would make every re-lock differ.
    grep -v -E '^ +#   -c ' "$output.tmp"
  } > "$output"
  rm -f "$output.tmp"
}

compile requirements.lock                      # runtime dependencies only
# runtime + development tools (tests, lint, audit) + the streamlit viewer (its tests need it)
compile requirements-dev.lock --extra dev --extra dashboard
echo "Wrote requirements.lock and requirements-dev.lock"
